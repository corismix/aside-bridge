/**
 * Provider id → mark, mirroring the map at the end of Aside's `icons-*.js`.
 *
 * Ids that are not here fall through to `ClusterMark`, which is the desktop
 * app's own behaviour rather than an omission.
 */
const PROVIDER_MARKS: Record<
  string,
  (props: MarkProps) => React.ReactElement
> = {
  aside: AsideSymbol,
  anthropic: AnthropicMark,
  'claude-code': ClaudeMark,
  openai: OpenAIMark,
  'openai-codex': OpenAIMark,
  'openai-codex-oauth': OpenAIMark,
  google: GoogleMark,
  'google-ai-studio': GoogleMark,
  'google-vertex-ai': GoogleMark,
  xai: XaiMark,
  'xai-grok-oauth': GrokMark,
  grok: GrokMark,
  opencode: OpenCodeMark,
  'opencode-zen': OpenCodeMark,
};

/** The mark for a provider id, at whatever size the caller needs. */
export function ProviderMark({
  id,
  size = 15,
  className,
}: {
  id: string;
  size?: number;
  className?: string;
}) {
  const Mark = PROVIDER_MARKS[id] || ClusterMark;
  return <Mark size={size} className={className} />;
}

/** True when we draw a provider's real brand mark rather than the fallback. */
export function hasProviderMark(id: string): boolean {
  return Boolean(PROVIDER_MARKS[id]);
}
