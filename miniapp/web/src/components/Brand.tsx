/**
 * Brand marks, recreated from Aside's own shipped components.
 *
 * These replace the approximations that used to live in `Icons.tsx` -- a
 * hand-drawn circle-with-a-slash standing in for the Aside symbol, four
 * dots for "some provider", an eight-point asterisk for Claude. At 15px in
 * a picker row those read as placeholders, because that is what they were.
 *
 * What is here is the real path data, transcribed from the desktop app's
 * bundle (`official-brand-symbol-*.js`, `openai-*.js`, `claudeai-*.js`,
 * `google-*.js`, `icons-*.js`, `copilot-*.js`) and rewritten as our own
 * components. Only path geometry is copied: no fonts, no raster assets, no
 * bundled files. Every mark keeps Aside's own conventions -- a 24-unit
 * viewBox, `fill="currentColor"`, no intrinsic colour -- so they inherit
 * from whatever row they sit in and work in both themes.
 *
 * The provider→mark map at the bottom mirrors the one at the end of the
 * shipped `icons-*.js`, including its fallback: providers Aside has no
 * dedicated mark for (Cerebras among them -- the bundle names it "Cerebras
 * AI" but ships no icon) get the generic cluster glyph, which is exactly
 * what the desktop model picker draws for them.
 */

export interface MarkProps {
  size?: number;
  className?: string;
}

function svgProps(size: number, className?: string) {
  return {
    viewBox: '0 0 24 24',
    fill: 'none',
    width: size,
    height: size,
    className,
    'aria-hidden': true,
    focusable: 'false' as const,
  };
}

